extern common_handler

%macro idt_no_error 1
global idt_handler_%1
idt_handler_%1:
  ; Fake error code
  push 0
  ; Interrupt Number
  push %1
  ; Registers
  push rax
  push rbx
  push rcx
  push rdx
  push rbp
  push rdi
  push rsi
  push r8
  push r9
  push r10
  push r11
  push r12
  push r13
  push r14
  push r15
  ; Change Data Segment
  xor rax, rax
  mov ax, ds
  push rax
  mov ax, 0x10
  mov ds, ax
  mov es, ax
  mov ss, ax
  ; Pass in the context
  mov rdi, rsp

  call common_handler

  ; Pop Data segment
  ; We aren't setting ss since that gets set by iretq
  pop rax
  mov ds, ax
  mov es, ax
  ; Registers
  pop r15
  pop r14
  pop r13
  pop r12
  pop r11
  pop r10
  pop r9
  pop r8
  pop rsi
  pop rdi
  pop rbp
  pop rdx
  pop rcx
  pop rbx
  pop rax
  ; Pop error and interrupt code
  add rsp, 16
  ; Leave
  iretq
%endmacro

