static inline void register_int(uint8_t num, uintptr_t handler, uint8_t ist,
                                uint8_t dpl, uint8_t gate_type) {
  idt[num].ist = ist;
  idt[num].dpl = dpl;
  idt[num].gate_type = gate_type;

  idt[num].offset_1 = handler & 0xFF;
  idt[num].offset_2 = (handler >> 16) & 0xFF;
  idt[num].offset_3 = handler >> 32;
}

